import http from 'node:http';
import { LOOPBACK_MARKER_HEADER } from './verify.mjs';

const ERROR = 'Local identity verification unavailable.';
const fail = () => { throw new Error('IDENTITY_UNAVAILABLE'); };
const responseHeaders = new Set(['cache-control', 'pragma', 'referrer-policy', 'x-content-type-options',
  'content-security-policy', 'set-cookie', 'location', 'content-type']);
const deny = res => {
  if (res.headersSent) { res.destroy(); return; }
  res.writeHead(400, { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store', Connection: 'close' });
  res.end(ERROR);
};

// The target is an already-listening core in this namespace, never a caller URL.
// The ingress never trusts browser-supplied proxy headers. Its random marker is
// generated by the local runtime, stays in memory, and is not sent to browsers.
export function createLoopbackIngress(core, marker, { containerEdge = false } = {}) {
  const target = core.address();
  if (typeof containerEdge !== 'boolean' || !target || target.address !== '127.0.0.1' || !Number.isInteger(target.port) || target.port < 1 ||
      typeof marker !== 'string' || !/^[A-Za-z0-9_-]{43}$/.test(marker)) fail();
  let pending = 0; let closing;
  const upstreams = new Set();
  const server = http.createServer({ maxHeaderSize: 8192, headersTimeout: 5000, requestTimeout: 5000, keepAliveTimeout: 1 }, (req, res) => {
    if (closing || pending >= 4) { deny(res); return; }
    pending++;
    let upstream; let timer;
    const task = async () => {
      let hosts = 0; const seen = new Set();
      for (let i = 0; i < req.rawHeaders.length; i += 2) {
        const name = req.rawHeaders[i].toLowerCase();
        if (name === 'host') hosts++;
        if (name === 'forwarded' || name.startsWith('x-forwarded-') || name === LOOPBACK_MARKER_HEADER ||
            (['host', 'origin', 'cookie', 'content-type', 'content-length'].includes(name) && seen.has(name))) fail();
        seen.add(name);
      }
      if ((!containerEdge && !['127.0.0.1', '::1', '::ffff:127.0.0.1'].includes(req.socket.remoteAddress)) ||
          hosts !== 1 || req.headers.host !== 'localhost:17645' || !['GET', 'POST'].includes(req.method) ||
          req.headers['transfer-encoding'] !== undefined || req.headers.expect !== undefined || req.headers.upgrade !== undefined ||
          req.headers['content-encoding'] !== undefined || typeof req.url !== 'string' || req.url.length > 4096 ||
          !req.url.startsWith('/') || req.url.startsWith('//') || req.url.includes('#')) fail();
      const length = req.headers['content-length'];
      if (length !== undefined && (!/^(0|[1-9][0-9]{0,3})$/.test(length) || Number(length) > 1024)) fail();
      if (req.method === 'GET' && length !== undefined && length !== '0') fail();
      let bytes = 0; const chunks = [];
      const requestDeadline = setTimeout(() => req.destroy(), 5000);
      try { for await (const chunk of req) { bytes += chunk.length; if (bytes > 1024) fail(); chunks.push(chunk); } }
      finally { clearTimeout(requestDeadline); }
      if (req.method === 'GET' && bytes !== 0) fail();
      const headers = { Host: 'localhost:17645', [LOOPBACK_MARKER_HEADER]: marker, Connection: 'close' };
      for (const name of ['origin', 'cookie', 'content-type']) if (req.headers[name] !== undefined) headers[name] = req.headers[name];
      if (req.method === 'POST') headers['Content-Length'] = bytes;
      await new Promise((resolve, reject) => {
        upstream = http.request({ host: '127.0.0.1', port: target.port, path: req.url, method: req.method, headers, agent: false }, reply => {
          let size = 0; const body = [];
          reply.on('error', reject); reply.on('aborted', () => reject(new Error(ERROR)));
          reply.on('data', chunk => { size += chunk.length; if (size > 16384) { reply.destroy(); reject(new Error(ERROR)); } else body.push(chunk); });
          reply.on('end', () => {
            try {
              if (![200, 303, 400].includes(reply.statusCode) ||
                  (reply.headers.location !== undefined && !['/authorize', '/confirm'].includes(reply.headers.location))) fail();
              const safeHeaders = { Connection: 'close' };
              for (const [name, value] of Object.entries(reply.headers)) if (responseHeaders.has(name)) safeHeaders[name] = value;
              res.writeHead(reply.statusCode, safeHeaders); res.end(Buffer.concat(body)); resolve();
            } catch { reject(new Error(ERROR)); }
          });
        });
        upstreams.add(upstream); upstream.on('error', reject);
        timer = setTimeout(() => upstream.destroy(new Error(ERROR)), 20000);
        upstream.end(Buffer.concat(chunks));
      });
    };
    void task().catch(() => deny(res)).finally(() => {
      clearTimeout(timer); if (upstream) { upstreams.delete(upstream); upstream.destroy(); } pending--;
    });
  });
  server.maxConnections = 4; server.maxRequestsPerSocket = 1;
  server.on('clientError', (_error, socket) => socket.destroy());
  server.on('connect', (_req, socket) => socket.destroy());
  server.on('upgrade', (_req, socket) => socket.destroy());
  server.on('checkContinue', (_req, res) => deny(res));
  const close = () => closing ??= new Promise(resolve => {
    if (!server.listening) { for (const request of upstreams) request.destroy(); resolve(); return; }
    const grace = setTimeout(() => { server.closeAllConnections(); for (const request of upstreams) request.destroy(); }, 2000);
    server.close(() => { clearTimeout(grace); resolve(); }); server.closeIdleConnections();
  });
  return { server, close };
}
